import fs from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { createNotices } from './notices.mjs';
import {brandWindowsFile} from './windows-branding.mjs';
const root = path.dirname(path.dirname(fileURLToPath(import.meta.url)));
process.chdir(root);
const { version } = JSON.parse(await fs.readFile('package.json', 'utf8'));
const output = path.join(root, 'release', `Pinwheel-${version}-win-x64`);
if (await fs.stat(output).catch(() => null)) throw Error('Release folder already exists; choose a new version instead of overwriting a release.');
if (process.platform !== 'win32') throw Error('Windows directory packaging requires Windows. Use build:main and package-macos.py for macOS archives.');
await import('./build-main.mjs');
await fs.mkdir(output, { recursive: true });
await fs.cp(path.join(root, 'node_modules/electron/dist'), output, { recursive: true });
await fs.rename(path.join(output, 'electron.exe'), path.join(output, 'pinwheel.exe'));
const branding=await brandWindowsFile(path.join(output,'pinwheel.exe'),path.join(root,'assets/pinwheel.ico'),version);
await fs.writeFile(path.join(output,'windows-branding.json'),JSON.stringify(branding,null,2)+'\n');
const resources = path.join(output, 'resources', 'app');
await fs.mkdir(path.join(resources, 'desktop'), { recursive: true });
await fs.copyFile('.cache/main-bundle/main.mjs', path.join(resources, 'desktop', 'main.mjs'));
await fs.copyFile('desktop/preload.cjs', path.join(resources, 'desktop', 'preload.cjs'));
await fs.cp('dist', path.join(resources, 'dist'), { recursive: true });
await fs.writeFile(path.join(resources, 'package.json'), JSON.stringify({ name: 'pinwheel', version, license: 'MIT', type: 'module', main: 'desktop/main.mjs' }, null, 2));
await fs.cp('pet-examples', path.join(output, '示例宠物'), { recursive: true });
await fs.cp('themes', path.join(output, '示例主题'), { recursive: true });
await fs.writeFile(path.join(output, '使用说明.md'), (await fs.readFile('README.md','utf8')).replaceAll('(LICENSE)','(LICENSE-pinwheel.txt)'));
await fs.mkdir(path.join(output,'docs'),{recursive:true});
for(const name of ['images','audit-2026-10-26','security-2026-10-26'])await fs.cp(path.join('docs',name),path.join(output,'docs',name),{recursive:true});
for(const name of ['GITHUB-PUBLISH.md','BRANDING.md'])await fs.copyFile('docs/'+name,path.join(output,'docs',name));
for(const file of ['CONTRIBUTING.md','SECURITY.md'])await fs.copyFile(file,path.join(output,file));
await fs.copyFile('assets/pinwheel.ico', path.join(output, 'pinwheel.ico'));
await createNotices(path.join(root, 'node_modules'), path.join(output, 'THIRD-PARTY-NOTICES.md'));
await fs.cp('third-party', path.join(output, 'third-party'), { recursive: true });
for (const file of ['LICENSE','NOTICE.md']) await fs.copyFile(file, path.join(output, file === 'LICENSE' ? 'LICENSE-pinwheel.txt' : file));
console.log(output);
